# Arithmetic operator: Addition

a = 10
b = 20
print(a + b)

# Subtraction
print(b - a)

# Multiplication
print(a * b)

# Division
print(b / a)

# Modulus
print(b % a)            # The remainder of 2 numbers

# Exponentiation
x = 5
y = 3
print(x ** y)           # 5 to the power of 3

# Floor division
sum1 = 15
sum2 = 2
print(sum1 // sum2)     # Rounds up the number output without the point values


# Assignment operator

a = 5
sum = a + 5
print(sum)

a += 10         # short way of doing addition
print(a)

b = 10
b -= 10         # short way of doing subtraction
print(b)

x = 5
y = 3
print(x == y)       # 1 equal sign is used for assigning number, 2 equal sign for equal to
