print('Hello, World!')      #Both single quote and double quote works

print(420)      #Prints as integer type

print("420")        #Prints as string type

'''Triple single or double quote is used for multiline commenting.
Even though it's not exactly commenting rule of python, when we try to run the code,
interpreter take the lines as string which is not under any function so it just avoids the lines'''